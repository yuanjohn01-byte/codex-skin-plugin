var (
	semverPattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-((?:0|[1-9][0-9]*|[0-9]*[A-Za-z-][0-9A-Za-z-]*)(?:\.(?:0|[1-9][0-9]*|[0-9]*[A-Za-z-][0-9A-Za-z-]*))*))?$`)
	publicID      = regexp.MustCompile(`^[0-9]{6}$`)
	keyID         = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{2,63}$`)
	digest        = regexp.MustCompile(`^[0-9a-f]{64}$`)
	color         = regexp.MustCompile(`^#[0-9A-F]{6}(?:[0-9A-F]{2})?$`)
	assetPath     = regexp.MustCompile(`^assets/[0-9a-f]{64}\.(png|jpg|webp)$`)
)

